#!/usr/bin/env python3
"""Rebuild the input-code table of the device-control vocabulary from a kernel header.

    python scripts/refresh_device_input_codes.py <input-event-codes.h> --tag v6.12 [--check]

The vocabulary (docs/DEVICE_CONTROLS.md) names the input a control sends by its Linux
input event name (``BTN_SOUTH``, ``ABS_HAT0X``, ``SW_LID``). This reads the names and
their numbers from the kernel's user-space header
``include/uapi/linux/input-event-codes.h`` and writes
``src/y4d_spec/device/input-codes.json``: one map per event type, name to number, with
the tag and the header's sha256 so the table says exactly what it was read from.

Only ``#define NAME value`` lines are read. A value is a number or another name defined
earlier (``BTN_A`` is ``BTN_SOUTH``); anything else (``KEY_MAX+1``) is skipped, and so
are the ``_MAX``, ``_CNT`` and ``_MIN_INTERESTING`` bookkeeping names and the
``_RESERVED`` placeholders (``KEY_RESERVED``, ``REL_RESERVED``, ``ABS_RESERVED``), which
name no input a control can send. The header is not copied: the table holds only the
names and numbers a program must agree on with the kernel, and it records the header's
own ``SPDX-License-Identifier`` line as it reads it. ``--check`` compares instead of
writing, and fails on a difference. It needs a copy of the header, which this repository
does not carry.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "src" / "y4d_spec" / "device" / "input-codes.json"
HEADER_PATH = "include/uapi/linux/input-event-codes.h"

#: name prefix -> the event type a code with that prefix belongs to
PREFIX_TYPE = {
    "KEY": "EV_KEY", "BTN": "EV_KEY", "REL": "EV_REL", "ABS": "EV_ABS",
    "SW": "EV_SW", "LED": "EV_LED",
}
EVENT_TYPES = ("EV_KEY", "EV_REL", "EV_ABS", "EV_SW", "EV_LED")
DEFINE = re.compile(r"^#define\s+([A-Z][A-Z0-9_]*)\s+(\S+)")
SKIP = re.compile(r"_(MAX|CNT|MIN_INTERESTING|RESERVED)$")
SPDX = re.compile(r"SPDX-License-Identifier:\s*(.+?)\s*(?:\*/)?\s*$")
CONTENTS = (
    "This table holds only names and numbers, generated from {file} at {tag} by "
    "scripts/refresh_device_input_codes.py; no text of the header is copied. The "
    "header's SPDX-License-Identifier line is {spdx}."
)


def read_spdx(text: str) -> str:
    """The value of the header's own ``SPDX-License-Identifier`` line, as written."""
    for line in text.splitlines()[:5]:
        m = SPDX.search(line)
        if m:
            return m.group(1)
    raise SystemExit("refresh_device_input_codes: the header has no SPDX-License-Identifier line")


def read_header(text: str) -> dict:
    values: dict[str, int] = {}
    for line in text.splitlines():
        m = DEFINE.match(line)
        if not m:
            continue
        name, raw = m.group(1), m.group(2)
        try:
            values[name] = int(raw, 0)
        except ValueError:
            if raw in values:
                values[name] = values[raw]
    codes: dict[str, dict[str, int]] = {t: {} for t in EVENT_TYPES}
    for name, value in values.items():
        prefix = name.split("_", 1)[0]
        if prefix in PREFIX_TYPE and not SKIP.search(name):
            codes[PREFIX_TYPE[prefix]][name] = value
    return {
        "event_types": {t: values[t] for t in EVENT_TYPES},
        "codes": {t: dict(sorted(codes[t].items(), key=lambda kv: (kv[1], kv[0])))
                  for t in EVENT_TYPES},
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("header", type=Path, help="a copy of " + HEADER_PATH)
    ap.add_argument("--tag", required=True, help="the kernel tag the copy was taken at")
    ap.add_argument("--check", action="store_true", help="compare, do not write")
    args = ap.parse_args()

    raw = args.header.read_bytes()
    text = raw.decode("utf-8")
    spdx = read_spdx(text)
    table = {
        "note": "GENERATED by scripts/refresh_device_input_codes.py. Do not edit.",
        "source": {
            "project": "Linux kernel",
            "file": HEADER_PATH,
            "tag": args.tag,
            "sha256": hashlib.sha256(raw).hexdigest(),
            "spdx_license_identifier": spdx,
        },
        "contents": CONTENTS.format(file=HEADER_PATH, tag=args.tag, spdx=spdx),
        **read_header(text),
    }
    out = json.dumps(table, indent=1) + "\n"
    if args.check:
        if TABLE.read_text(encoding="utf-8") != out:
            print("refresh_device_input_codes: FAIL — the table differs from the header")
            return 1
        print("refresh_device_input_codes: ok")
        return 0
    TABLE.write_text(out, encoding="utf-8")
    counts = ", ".join(f"{t}={len(table['codes'][t])}" for t in EVENT_TYPES)
    print(f"wrote {TABLE.relative_to(ROOT)} ({counts})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
